// Writes supabase/seed-ingredients.sql from src/data/ingredients.js.
// Run the SQL in the Supabase SQL editor; existing entries are updated.
import { writeFileSync } from 'node:fs'
import { SEED_INGREDIENTS } from '../src/data/ingredients.js'

const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`)
const rows = SEED_INGREDIENTS.map(
  (e) => `  (${q(e.name)}, ${q(e.aisle)}, ${q(e.image)}, ${q(e.base)}, array[${e.aliases.map(q).join(', ')}]::text[])`,
)
const sql = `-- Generated by npm run seed:ingredients from src/data/ingredients.js
insert into public.ingredients (name, aisle, image, base, aliases) values
${rows.join(',\n')}
on conflict (coalesce(household_id, '00000000-0000-0000-0000-000000000000'::uuid), lower(name)) do update set aisle = excluded.aisle, image = excluded.image, base = excluded.base, aliases = excluded.aliases, updated_at = now();
`
writeFileSync(new URL('../supabase/seed-ingredients.sql', import.meta.url), sql)
console.log(`${rows.length} ingredients written to supabase/seed-ingredients.sql`)
